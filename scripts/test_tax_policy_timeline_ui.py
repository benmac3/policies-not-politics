#!/usr/bin/env python3
"""Browser smoke tests. Requires playwright and Chromium; no network access needed."""
from pathlib import Path
import json
import os
import shutil
from playwright.sync_api import sync_playwright
ROOT=Path(__file__).resolve().parents[1]
OUT=ROOT/'reviews/generated'
checks=[]
def check(condition, label):
    if not condition: raise AssertionError(label)
    checks.append(label)
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True,executable_path=os.environ.get('CHROMIUM_EXECUTABLE') or shutil.which('chromium') or shutil.which('chromium-browser'),args=['--no-sandbox'])
    page=browser.new_page(viewport={'width':1440,'height':1250},device_scale_factor=1)
    errors=[];requests=[]
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.on('request',lambda r:requests.append(r.url))
    page.set_content((OUT/'federal-tax-policy-timeline.html').read_text(encoding='utf-8'))
    page.wait_for_selector('.eventrow')
    check(page.locator('.eventrow').count()==101,'All 101 records render')
    check('Bill introduced' in page.locator('#detail h2').inner_text(),'Initial selection is October trust bill')
    check('not verified enacted law' in page.locator('#detail .notice').inner_text(),'Proposal legal-status warning')
    check(page.locator('.stat').count()==6,'All six category cards')
    check(page.locator('#overview .marker').count()==101,'All timeline markers')
    check(page.evaluate('document.documentElement.scrollWidth <= innerWidth'),'No desktop horizontal overflow')
    page.screenshot(path=str(OUT/'tax-timeline-desktop.png'),full_page=True)
    page.select_option('#status','future')
    check(page.locator('.eventrow').count()==5,'Five future application records')
    page.select_option('#status','proposed')
    check(page.locator('.eventrow').count()==3,'Three proposal milestones')
    page.select_option('#status','interpretation')
    check(page.locator('.eventrow').count()==3,'Three judgments/guidance records')
    page.select_option('#status','context')
    check(page.locator('.eventrow').count()==7,'Six baselines plus one benchmark')
    page.click('#reset');page.select_option('#category','trusts')
    check(page.locator('.eventrow').count()==17,'Trust category includes cross-cutting records')
    page.fill('#search','Bendel');check(page.locator('.eventrow[data-id="trust-bendel"]').count()==1,'Search finds Bendel')
    page.locator('.eventrow[data-id="trust-bendel"]').click();check('Interpretation, not a new statute' in page.locator('#detail').inner_text(),'Judgment not labelled new legislation')
    page.click('#reset');page.select_option('#category','excise');page.fill('#search','tobacco')
    check(page.locator('.eventrow').count()>5,'Excise and text filters combine')
    page.click('#reset');page.fill('#search','zzzz-no-result')
    check(page.locator('.eventrow').count()==0,'Empty search result state')
    check('No event selected' in page.locator('#detail').inner_text(),'Empty detail state')
    page.click('#reset');page.locator('.eventrow[data-id="income-2026"]').click()
    check(page.locator('.ratetable tbody tr').count()==5,'Five income-tax bands')
    check('$4,020' in page.locator('.ratetable').inner_text(),'2026 basic-tax boundary arithmetic')
    page.select_option('#ratepick','income-2027')
    check('15% to 14%' in page.locator('#detail h2').inner_text(),'Schedule selector jumps to future law')
    check('$3,752' in page.locator('.ratetable').inner_text(),'2027 basic-tax boundary arithmetic')
    check('future application' in page.locator('#detail .notice').inner_text(),'Enacted future status warning')
    page.select_option('#ratepick','income-2024')
    check('$4,288' in page.locator('.ratetable').inner_text(),'2024 basic-tax boundary arithmetic')
    page.screenshot(path=str(OUT/'tax-timeline-income-rates.png'),full_page=True)
    page.click('#recent')
    check(page.locator('.eventrow').count()==16,'2026 reforms shortcut includes scheduled dates')
    check('receives assent' in page.locator('#detail h2').inner_text(),'2026 shortcut selects enacted first tranche')
    page.locator('#detail [data-jump="gearing-2027"]').click()
    check('Rental-loss quarantine' in page.locator('#detail h2').inner_text(),'Related-milestone navigation')
    page.click('#reset');page.fill('#from','1980');page.locator('#from').dispatch_event('change')
    page.fill('#to','1989');page.locator('#to').dispatch_event('change')
    check(all('198' in x.inner_text() for x in page.locator('.eventrow time').all()),'Year-range filter')
    page.fill('#from','2028');page.locator('#from').dispatch_event('change')
    check(page.locator('.eventrow').count()==0,'Inverted range returns empty rather than invalid records')
    page.click('#reset');page.select_option('#order','oldest')
    check('1960' in page.locator('.eventrow').first.inner_text(),'Oldest-first sorting')
    page.locator('#overview [data-id="gst-start"]').focus();page.keyboard.press('Enter')
    check('GST introduced at 10%' in page.locator('#detail h2').inner_text(),'Keyboard marker selection')
    page.locator('#detail .sources summary').click()
    check(page.locator('#detail .sources a').count()==2,'Source disclosure links')
    with page.expect_download() as download: page.click('#json')
    check(download.value.suggested_filename=='federal-tax-policy-timeline.json','JSON export')
    path=download.value.path();exported=json.loads(Path(path).read_text())
    check(len(exported['events'])==101,'JSON export data integrity')
    page.select_option('#status','proposed')
    with page.expect_download() as download:page.click('#csv')
    check(download.value.suggested_filename=='filtered-tax-events.csv','Filtered CSV export')
    import csv
    with Path(download.value.path()).open() as f:rows=list(csv.DictReader(f))
    check(len(rows)==3 and all(r['status']=='proposed' for r in rows),'CSV respects current filters')
    page.click('#reset');page.set_viewport_size({'width':390,'height':844})
    check(page.evaluate('document.documentElement.scrollWidth <= innerWidth'),'No mobile page overflow')
    page.screenshot(path=str(OUT/'tax-timeline-mobile.png'),full_page=True)
    page.locator('.eventrow[data-id="income-2026"]').click()
    check(page.evaluate('document.documentElement.scrollWidth <= innerWidth'),'No mobile rate-table overflow')
    check(not errors,'No JavaScript page errors')
    check(not requests,'Fully offline: no external requests')
    report={'passed':True,'check_count':len(checks),'checks':checks,'console_errors':errors,'external_requests':requests,'desktop':[1440,1250],'mobile':[390,844],'browser':'Chromium via Playwright'}
    (OUT/'ui-test-report.json').write_text(json.dumps(report,indent=2)+'\n')
    print(json.dumps(report,indent=2));browser.close()
